(function () {
  const slider = document.getElementById('heroSlider');
  if (!slider) return;
  if (slider.dataset.sliderInited) return;
  slider.dataset.sliderInited = '1';

  const track    = document.getElementById('heroTrack');
  const slides   = track.querySelectorAll('.hero-slide');
  const prev     = document.getElementById('heroPrev');
  const next     = document.getElementById('heroNext');
  const dotsWrap = document.getElementById('heroDots');
  if (!slides.length) return;

  let current = 0;
  let timer = null;

  dotsWrap.innerHTML = '';
  slides.forEach((_, i) => {
    const dot = document.createElement('button');
    dot.className = 'hero-slider__dot' + (i === 0 ? ' active' : '');
    dot.setAttribute('aria-label', 'Слайд ' + (i + 1));
    dot.addEventListener('click', () => goTo(i));
    dotsWrap.appendChild(dot);
  });
  const dots = dotsWrap.querySelectorAll('.hero-slider__dot');

  function render() {
    track.style.transform = 'translateX(-' + (current * 100) + '%)';
    dots.forEach((d, idx) => d.classList.toggle('active', idx === current));
  }
  function goTo(i) {
    current = (i + slides.length) % slides.length;
    render();
    restart();
  }
  const nextSlide = () => goTo(current + 1);
  const prevSlide = () => goTo(current - 1);

  prev.addEventListener('click', prevSlide);
  next.addEventListener('click', nextSlide);

  function start()   { stop(); timer = setInterval(nextSlide, 4000); }
  function stop()    { if (timer) { clearInterval(timer); timer = null; } }
  function restart() { start(); }
  start();
  slider.addEventListener('mouseenter', stop);
  slider.addEventListener('mouseleave', start);

  slides.forEach(slide => {
    const href = slide.dataset.href;
    if (!href) return;
    slide.addEventListener('click', (e) => {
      if (e.target.closest('a, button')) return;
      const target = document.querySelector(href);
      if (target) target.scrollIntoView({ behavior: 'smooth' });
    });
  });

  let startX = 0;
  track.addEventListener('touchstart', e => { startX = e.touches[0].clientX; }, { passive: true });
  track.addEventListener('touchend', e => {
    const diff = e.changedTouches[0].clientX - startX;
    if (Math.abs(diff) > 50) (diff < 0 ? nextSlide() : prevSlide());
  });
})();

