(function () {
  if (!('IntersectionObserver' in window)) return;   

  const targets = document.querySelectorAll(
    '.hero-slider, .section, .catalog-grid--sub, .sort-bar, .policy-content, .account-grid, .account-gate__box, .how-stop'
  );
  if (!targets.length) return;

  targets.forEach(el => el.classList.add('reveal'));   

  const io = new IntersectionObserver((entries) => {
    entries.forEach(e => {
      if (e.isIntersecting) {
        e.target.classList.add('in-view');   
        io.unobserve(e.target);             
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -8% 0px' });

  targets.forEach(el => io.observe(el));
})();

(function () {
  const hero = document.getElementById('heroSlider');
  if (!hero) return;
  if (hero.dataset.auroraInited) return;    
  hero.dataset.auroraInited = '1';

  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  const aurora = document.createElement('div');
  aurora.className = 'hero-aurora';
  aurora.innerHTML = '<span></span><span></span><span></span>';
  hero.insertBefore(aurora, hero.firstChild);

  if (reduce) return;   

  const icons = () => hero.querySelectorAll('.hero-slide__icon');
  let mx = 0, my = 0, sy = 0, ticking = false;

  function apply() {
    ticking = false;
  
    aurora.style.transform =
      'translate(' + (mx * 16) + 'px,' + (my * 16 + sy * 0.05) + 'px)';

    icons().forEach(ic => {
      ic.style.transform = 'translate(' + (mx * -12) + 'px,' + (my * -12) + 'px)';
    });
  }
  function req() { if (!ticking) { ticking = true; requestAnimationFrame(apply); } }

  hero.addEventListener('mousemove', e => {
    const r = hero.getBoundingClientRect();
    mx = (e.clientX - r.left) / r.width - 0.5;   
    my = (e.clientY - r.top) / r.height - 0.5;
    req();
  }, { passive: true });
  hero.addEventListener('mouseleave', () => { mx = 0; my = 0; req(); });

  window.addEventListener('scroll', () => {
    sy = window.scrollY;
    if (sy < hero.offsetHeight + 200) req();      
  }, { passive: true });
})();

(function () {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

  let tiltCard = null;
  let ticking = false;
  let lastE = null;

  function applyTilt() {
    ticking = false;
    if (!tiltCard || !lastE) return;
    const r = tiltCard.getBoundingClientRect();
    const px = (lastE.clientX - r.left) / r.width - 0.5;   
    const py = (lastE.clientY - r.top) / r.height - 0.5;
    const ry = px * 8;    
    const rx = -py * 8;    
    tiltCard.style.transform =
      'perspective(900px) rotateX(' + rx.toFixed(2) + 'deg) rotateY(' + ry.toFixed(2) + 'deg) translateY(-6px)';
  }
  function req() { if (!ticking) { ticking = true; requestAnimationFrame(applyTilt); } }

  document.addEventListener('mousemove', e => {
    const c = e.target.closest('.product-card');
    if (c !== tiltCard) {
      if (tiltCard) tiltCard.style.transform = '';  
      tiltCard = c;
    }
    if (!c) return;
    lastE = e;
    req();
  }, { passive: true });

  document.addEventListener('mouseout', e => {
    if (!e.relatedTarget && tiltCard) { tiltCard.style.transform = ''; tiltCard = null; }
  });
})();
